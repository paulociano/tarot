export function relation(x,y){
 const a=study(x.id),b=study(y.id);const shared=a.themes.filter(t=>b.themes.includes(t));const themes=[...new Set([...a.themes,...b.themes])];
 if(x.isReversed||y.isReversed)return {label:'Tensão e revisão',text:'A orientação invertida convida a examinar como '+a.archetype+' e '+b.archetype+' podem exigir ajustes, limites ou outra perspectiva.',themes};
 if(shared.length)return {label:'Reforço temático',text:'Os dois arcanos compartilham '+shared.join(', ')+'. Observe como esse tema assume formas diferentes: '+a.archetype+' e '+b.archetype+'.',themes};
 if(x.rank===y.rank&&x.arcana==='Menor'&&y.arcana==='Menor')return {label:'Eco numérico',text:'As cartas compartilham o mesmo grau do naipe, mas expressam '+a.archetype+' e '+b.archetype+' em domínios distintos.',themes};
 if(x.element===y.element)return {label:'Afinidade simbólica',text:'O eixo '+x.element+' aproxima '+a.archetype+' de '+b.archetype+'. Compare os modos de manifestar esse eixo.',themes};
 return {label:'Complementaridade possível',text:'Coloque '+a.archetype+' em diálogo com '+b.archetype+'; procure uma relação contextual sem pressupor que um símbolo cause o outro.',themes};
}
